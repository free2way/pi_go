export interface LocalizableError {
  code?: string;
  message?: string;
}

/**
 * Localizes a server error: a known `code` wins, otherwise the server's own
 * `message`, otherwise `fallback` (then `error.generic`).
 */
export function localizeError(locale: Locale, error: LocalizableError | null | undefined, fallback = ""): string {
  const key = error?.code ? ERROR_CODE_KEYS[error.code] : undefined;
  if (key) return t(locale, key);
  const message = error?.message?.trim();
  if (message) return message;
  if (fallback) return fallback;
  return t(locale, "error.generic");
}






